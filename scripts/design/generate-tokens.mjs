#!/usr/bin/env node

import {
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const defaultRepoRoot = fileURLToPath(new URL('../..', import.meta.url));
const generatedTokensPath = 'src/design/tokens.ts';
const sourceTokensPath = 'design-tokens.json';
const optionalGeneratedCssPath = 'tokens.css';
const rawDesignCssPath = 'docs/design/v1/raw/tokens.css';

function repoRelative(repoRoot, path) {
  return relative(repoRoot, path).replaceAll('\\', '/');
}

function readJson(path) {
  return JSON.parse(readFileSync(path, 'utf8'));
}

function toCamelCase(key) {
  return key.replace(/-([a-z0-9])/g, (_match, char) => char.toUpperCase());
}

function normalizeDimension(value) {
  const match = /^(-?\d+(?:\.\d+)?)(pt|px|ms)$/.exec(value);

  if (!match) {
    return value;
  }

  return Number(match[1]);
}

function normalizeTokenValue(value) {
  if (typeof value === 'string') {
    return normalizeDimension(value);
  }

  if (Array.isArray(value)) {
    return value.map(normalizeTokenValue);
  }

  if (!value || typeof value !== 'object') {
    return value;
  }

  return Object.fromEntries(
    Object.entries(value).map(([key, child]) => [toCamelCase(key), normalizeTokenValue(child)]),
  );
}

function normalizeTokenGroup(group) {
  if (Array.isArray(group) || !group || typeof group !== 'object') {
    return normalizeTokenValue(group);
  }

  if ('$value' in group) {
    return normalizeTokenValue(group.$value);
  }

  return Object.fromEntries(
    Object.entries(group)
      .filter(([key]) => !key.startsWith('$'))
      .map(([key, value]) => [toCamelCase(key), normalizeTokenGroup(value)]),
  );
}

function numberContract(contract, key) {
  const value = contract?.[key];

  if (typeof value !== 'number') {
    throw new Error(`design-tokens.json contract.${key} must be a number`);
  }

  return value;
}

function buildBusinessTokens(contract) {
  return {
    noStreaksDays: numberContract(contract, 'no-streaks-days'),
    quickLogPosition: contract['quick-log-position'],
    quickLogTrackersMax: numberContract(contract, 'quick-log-trackers-max'),
    tabs: contract.tabs,
    timing: {
      accidentalDoubleTapWindowSeconds: numberContract(
        contract,
        'accidental-double-tap-window-seconds',
      ),
      duplicateCareWarningWindowSeconds: numberContract(
        contract,
        'duplicate-warning-window-seconds',
      ),
    },
    todayDailyCardsMax: numberContract(contract, 'today-daily-cards-max'),
  };
}

function normalizeTypography(sourceTypography) {
  const typography = normalizeTokenGroup(sourceTypography);

  typography.scale = Object.fromEntries(
    Object.entries(typography.scale ?? {}).map(([key, style]) => [
      key,
      {
        ...style,
        letterSpacing: style.letterSpacing ?? 0,
      },
    ]),
  );

  return typography;
}

export function buildTokenPayload(source) {
  return {
    business: buildBusinessTokens(source.contract ?? {}),
    color: normalizeTokenGroup(source.color),
    component: normalizeTokenGroup(source.component),
    elevation: normalizeTokenGroup(source.elevation),
    haptic: normalizeTokenGroup(source.haptic),
    icon: normalizeTokenGroup(source.icon),
    layout: normalizeTokenGroup(source.layout),
    motion: normalizeTokenGroup(source.motion),
    radius: normalizeTokenGroup(source.radius),
    space: normalizeTokenGroup(source.space),
    typography: normalizeTypography(source.typography),
  };
}

export function renderTokensModule(payload) {
  return `// Generated by scripts/design/generate-tokens.mjs. Do not edit directly.
// Source: design-tokens.json.

export const tokens = ${JSON.stringify(payload, null, 2)} as const;

export const businessTiming = tokens.business.timing;

export type DesignTokens = typeof tokens;
export type BusinessTimingTokens = typeof businessTiming;
`;
}

function flattenCssLeaves(value, path = []) {
  if (Array.isArray(value)) {
    return [];
  }

  if (!value || typeof value !== 'object') {
    return [[path, value]];
  }

  return Object.entries(value).flatMap(([key, child]) => flattenCssLeaves(child, [...path, key]));
}

function toKebabCase(key) {
  return key.replace(/[A-Z]/g, (char) => `-${char.toLowerCase()}`);
}

function cssVariablePath(path) {
  return path.map(toKebabCase).join('-');
}

function cssValue(group, path, value) {
  if (typeof value === 'number') {
    if (group === 'motion' && path[0] === 'duration') {
      return `${value}ms`;
    }

    if (group === 'typography' && path.at(-1) === 'fontWeight') {
      return String(value);
    }

    return `${value}px`;
  }

  return String(value);
}

function normalizeCssComparisonValue(value) {
  return String(value)
    .trim()
    .replace(/\s*,\s*/g, ',')
    .replace(/\s+/g, ' ');
}

function normalizeGeneratedFile(value) {
  return String(value).replace(/\r\n?/g, '\n');
}

function readCssCustomProperties(css) {
  const properties = new Map();
  const propertyPattern = /(--[A-Za-z0-9_-]+)\s*:\s*([^;]+);/g;

  for (const match of css.matchAll(propertyPattern)) {
    properties.set(match[1], normalizeCssComparisonValue(match[2]));
  }

  return properties;
}

