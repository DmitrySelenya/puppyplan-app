function checkRawDesignCssDrift(path, payload, repoRoot) {
  const actual = readCssCustomProperties(readFileSync(path, 'utf8'));
  const errors = [];

  for (const [variable, expected] of Object.entries(rawDesignCssVariables(payload))) {
    const actualValue = actual.get(variable);
    const expectedValue = normalizeCssComparisonValue(expected);

    if (actualValue === undefined) {
      errors.push(`${variable} is missing`);
      continue;
    }

    if (actualValue !== expectedValue) {
      errors.push(`${variable} is ${actualValue}, expected ${expectedValue}`);
    }
  }

  if (errors.length > 0) {
    throw new Error(`${repoRelative(repoRoot, path)} drift: ${errors.join('; ')}`);
  }
}

export function renderTokensCss(payload) {
  const cssRoots = {
    color: payload.color,
    layout: payload.layout,
    motion: payload.motion,
    radius: payload.radius,
    space: payload.space,
    typography: payload.typography,
  };
  const lines = [
    '/* Generated by scripts/design/generate-tokens.mjs. Do not edit directly. */',
    ':root {',
  ];

  for (const [group, value] of Object.entries(cssRoots)) {
    for (const [path, leaf] of flattenCssLeaves(value)) {
      if (typeof leaf === 'object') {
        continue;
      }

      lines.push(`  --pp-${group}-${cssVariablePath(path)}: ${cssValue(group, path, leaf)};`);
    }
  }

  lines.push('}');
  lines.push('');

  return lines.join('\n');
}

export function writeGeneratedTokens({ repoRoot = defaultRepoRoot, source = null } = {}) {
  const sourceTokens = source ?? readJson(join(repoRoot, sourceTokensPath));
  const payload = buildTokenPayload(sourceTokens);
  const output = renderTokensModule(payload);
  const outputPath = join(repoRoot, generatedTokensPath);

  mkdirSync(join(repoRoot, 'src/design'), { recursive: true });
  writeFileSync(outputPath, output);

  return {
    output,
    outputPath,
    payload,
  };
}

export function checkTokenDrift({ repoRoot = defaultRepoRoot } = {}) {
  const source = readJson(join(repoRoot, sourceTokensPath));
  const payload = buildTokenPayload(source);
  const expectedModule = renderTokensModule(payload);
  const actualModulePath = join(repoRoot, generatedTokensPath);

  if (!existsSync(actualModulePath)) {
    throw new Error(`${generatedTokensPath} drift: generated token module is missing`);
  }

  const actualModule = readFileSync(actualModulePath, 'utf8');
  if (normalizeGeneratedFile(actualModule) !== normalizeGeneratedFile(expectedModule)) {
    throw new Error(`${generatedTokensPath} drift: run npm run tokens:generate`);
  }

  const checkedCss = [];
  const generatedCssPath = join(repoRoot, optionalGeneratedCssPath);
  if (existsSync(generatedCssPath)) {
    const actualCss = readFileSync(generatedCssPath, 'utf8');
    const expectedCss = renderTokensCss(payload);

    if (normalizeGeneratedFile(actualCss) !== normalizeGeneratedFile(expectedCss)) {
      throw new Error(`${optionalGeneratedCssPath} drift: run npm run tokens:generate and update CSS`);
    }

    checkedCss.push(repoRelative(repoRoot, generatedCssPath));
  }

  const rawCssPath = join(repoRoot, rawDesignCssPath);
  if (existsSync(rawCssPath)) {
    checkRawDesignCssDrift(rawCssPath, payload, repoRoot);
    checkedCss.push(repoRelative(repoRoot, rawCssPath));
  }

  return {
    checkedCss,
    checkedModule: repoRelative(repoRoot, actualModulePath),
  };
}

function runCli() {
  const checkOnly = process.argv.includes('--check');

  if (checkOnly) {
    const result = checkTokenDrift();
    const cssStatus = result.checkedCss.length > 0 ? `css=${result.checkedCss.join(',')}` : 'css=absent';
    console.log(`design tokens ok: ts=${result.checkedModule} ${cssStatus}`);
    return;
  }

  const result = writeGeneratedTokens();
  console.log(`generated ${repoRelative(defaultRepoRoot, result.outputPath)}`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  runCli();
}
